-- جداول سیستم شناسنامه
CREATE TABLE IF NOT EXISTS SystemCompanies (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Name NVARCHAR(200) NOT NULL DEFAULT '',
    Code NVARCHAR(100) NULL,
    Phone NVARCHAR(50) NULL,
    Address NVARCHAR(250) NULL,
    IsActive INTEGER NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS SystemDepartments (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Name NVARCHAR(150) NOT NULL DEFAULT '',
    CompanyId INTEGER NULL,
    ManagerName NVARCHAR(100) NULL,
    ManagerFamily NVARCHAR(100) NULL,
    StaffNumber NVARCHAR(50) NULL,
    Phone NVARCHAR(50) NULL,
    IsActive INTEGER NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS SystemUsers (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    FirstName NVARCHAR(100) NOT NULL DEFAULT '',
    LastName NVARCHAR(100) NULL DEFAULT '',
    StaffNumber NVARCHAR(50) NULL DEFAULT '',
    Username NVARCHAR(50) NULL,
    DepartmentId INTEGER NULL,
    CompanyId INTEGER NULL,
    AssignedToUserId INTEGER NULL,
    Role NVARCHAR(20) NULL DEFAULT 'User',
    IsActive INTEGER NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- جدول شناسنامه سیستم (دریافت از ایجنت)
CREATE TABLE IF NOT EXISTS SystemInfos (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    AgentId NVARCHAR(100) NOT NULL DEFAULT '',
    Motherboard NVARCHAR(250) NULL,
    Cpu NVARCHAR(200) NULL,
    Ram NVARCHAR(200) NULL,
    HardDisk NVARCHAR(250) NULL,
    Graphics NVARCHAR(200) NULL,
    Monitor NVARCHAR(200) NULL,
    IsApproved INTEGER NOT NULL DEFAULT 0,
    OsName NVARCHAR(100) NULL,
    TotalRamGb INTEGER NOT NULL DEFAULT 0,
    CompanyId INTEGER NULL,
    DepartmentId INTEGER NULL,
    UserId INTEGER NULL,
    ReceivedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
