    public static async Task<int> EnsureAiUserAsync(AppDbContext db)
    {
        var existing = await db.Users.FirstOrDefaultAsync(u => u.Username == AiUsername);
        if (existing != null)
        {
            // دستیار همیشه فعال و بدون دسترسی ورود می‌ماند.
            var changed = false;
            if (!existing.IsActive) { existing.IsActive = true; changed = true; }
            if (existing.FirstName != "هوش مصنوعی") { existing.FirstName = "هوش مصنوعی"; changed = true; }
            if (existing.LastName != "فروغ آریا") { existing.LastName = "فروغ آریا"; changed = true; }
            if (changed) await db.SaveChangesAsync();
            return existing.Id;
        }
        var ai = new User
        {
            Username = AiUsername,
            // رمز غیرقابل حدس و غیرقابل ورود — دستیار فقط از داخل کد پیام می‌فرستد.
            PasswordHash = "$AI$NO_LOGIN$" + Guid.NewGuid().ToString("N"),
            Role = "Operator",
            FirstName = "هوش مصنوعی",
            LastName = "فروغ آریا",
            IsActive = true,
        };
        db.Users.Add(ai);
        await db.SaveChangesAsync();
        return ai.Id;
    }

    public static async Task EnsureKnowledgeAsync(AppDbContext db)
    {
        foreach (var a in Articles)
        {
            var existing = await db.AiKnowledgeDocs.FirstOrDefaultAsync(d => d.DocKey == a.DocKey);
            if (existing == null)
            {
                db.AiKnowledgeDocs.Add(new AiKnowledgeDoc
                {
                    DocKey = a.DocKey,
                    Category = a.Category,
                    Title = a.Title,
                    Content = a.Content,
                    Link = a.Link,
                    IsActive = true,
                    UpdatedAtUtc = DateTime.UtcNow,
                });
            }
            else if (existing.Title != a.Title || existing.Content != a.Content
                     || existing.Category != a.Category || existing.Link != a.Link)
            {
                existing.Title = a.Title;
                existing.Content = a.Content;
                existing.Category = a.Category;
                existing.Link = a.Link;
                existing.IsActive = true;
                existing.EmbeddingJson = null; // محتوای تازه → امبدینگ دوباره ساخته می‌شود
                existing.UpdatedAtUtc = DateTime.UtcNow;
            }
        }
        await db.SaveChangesAsync();
    }

