    /// <summary>آیا برای این سال، فهرست تعطیلات قمری در کاتالوگ موجود است؟</summary>
    public static bool HasLunarData(int jy) => LunarByYear.ContainsKey(jy);

    /// <summary>
    /// فهرست کامل تعطیلات رسمی سال (ثابت شمسی + قمری) — اگر تاریخ تکراری باشد عنوان‌ها با « / » ترکیب می‌شوند
    /// (مثلاً ۱ فروردین ۱۴۰۵ = «عید نوروز / عید سعید فطر»).
    /// </summary>
    public static List<(int Month, int Day, string Name)> GetForYear(int jy)
    {
        var map = new SortedDictionary<int, string>();
        void Add(int m, int d, string name)
        {
            var key = m * 100 + d;
            map[key] = map.TryGetValue(key, out var prev) ? $"{prev} / {name}" : name;
        }

        foreach (var h in SolarFixed) Add(h.Month, h.Day, h.Name);
        if (LunarByYear.TryGetValue(jy, out var lunar))
            foreach (var h in lunar) Add(h.Month, h.Day, h.Name);

        return map.Select(kv => (kv.Key / 100, kv.Key % 100, kv.Value)).ToList();
    }
