"""Exercise the real Blazor components in Preview with clearly fictional API fixtures.
Run: python -m pip install playwright; python -m playwright install --with-deps chromium
Start Preview on port 5088, then python browser_test.py.
"""
import json
import os
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base = os.environ.get('SERVER_PREVIEW_URL', 'http://127.0.0.1:5088')
output = Path(__file__).parent / 'artifacts'
output.mkdir(exist_ok=True)
checks = []
errors = []
def passed(name):
    checks.append(name)
    print('PASS:', name)

with sync_playwright() as p:
    browser = p.chromium.launch(args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440, 'height':1050})
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(base + '/servers')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.locator('.infra-metric')).to_have_count(8)
    expect(page.locator('.server-table tbody tr')).to_have_count(8)
    passed('Dashboard: eight cards and eight fixture servers')
    page.get_by_role('button', name=re.compile('عدم دسترسی')).click()
    expect(page.locator('.server-table tbody tr')).to_have_count(1)
    expect(page.locator('.server-table tbody')).to_contain_text('Web-Production')
    expect(page.locator('.infra-metric.is-selected')).to_contain_text('عدم دسترسی')
    passed('Dashboard cards filter rows and selection state')
    page.get_by_role('button', name=re.compile('حذف فیلتر')).click()
    expect(page.locator('.server-table tbody tr')).to_have_count(8)
    search = page.get_by_role('textbox', name='جست‌وجوی سرورها')
    search.fill('Database'); search.press('Enter')
    expect(page.locator('.server-table tbody tr')).to_have_count(1)
    expect(page.locator('.infra-metric').first.locator('.infra-value')).to_have_text('۸')
    passed('Company total stays eight after filtering search to one server')
    search.fill('does-not-exist'); search.press('Enter')
    expect(page.get_by_role('heading', name='نتیجه‌ای پیدا نشد')).to_be_visible()
    passed('No search results are distinguished from an empty company')
    search.fill(''); search.press('Enter')
    expect(page.locator('.server-table tbody tr')).to_have_count(8)
    page.get_by_role('combobox', name='انتخاب شرکت').select_option('2')
    expect(page.locator('.infra-metric').first.locator('.infra-value')).to_have_text('۰')
    expect(page.get_by_role('heading', name='سروری ثبت نشده است')).to_be_visible()
    passed('Switching company clears old rows and dashboard totals')
    page.get_by_role('combobox', name='انتخاب شرکت').select_option('1')
    expect(page.locator('.server-table tbody tr')).to_have_count(8)
    page.screenshot(path=str(output / 'dashboard-desktop.png'))
    page.locator('.server-table').get_by_role('link', name='ESXi-Production-01').click()
    expect(page.get_by_role('heading', name='ESXi-Production-01', exact=True)).to_be_visible()
    expect(page.get_by_role('tab')).to_have_count(6)
    passed('List name opens dedicated detail route with six tabs')
    page.screenshot(path=str(output / 'server-detail-desktop.png'), full_page=True)
    page.get_by_role('tab', name='قطعات', exact=True).click()
    expect(page.locator('#detail-panel tbody tr')).to_have_count(6)
    page.locator('#detail-panel select').select_option('Disk')
    expect(page.locator('#detail-panel tbody tr')).to_have_count(1)
    passed('Hardware tab reads actual component contract and filters type')
    page.get_by_role('tab', name='روند سلامت', exact=True).click()
    expect(page.locator('.health-sample')).to_have_count(32)
    expect(page.locator('#detail-panel tbody tr')).to_have_count(32)
    passed('Health samples and timeline are rendered from fixture history')
    page.get_by_role('tab', name='رخدادهای iLO', exact=True).click()
    expect(page.locator('#detail-panel tbody')).to_contain_text('خودآزمایی')
    passed('Event tab works')
    page.get_by_role('tab', name='لاگ عملیات', exact=True).click()
    expect(page.locator('#detail-panel tbody tr')).to_have_count(8)
    passed('Operation log tab works')
    page.goto(base + '/servers/3')
    page.wait_for_selector('main[data-preview-ready="true"]')
    page.get_by_role('tab', name='هشدار و دستورکار', exact=True).click()
    expect(page.locator('#detail-panel tbody tr')).to_have_count(30)
    page.get_by_role('button', name='بعدی', exact=True).click()
    expect(page.locator('#detail-panel tbody tr')).to_have_count(5)
    page.get_by_role('button', name='قبلی', exact=True).click()
    expect(page.locator('#detail-panel tbody tr')).to_have_count(30)
    passed('Per-server alerts paginate 30 + 5 without losing total')
    page.get_by_role('button', name='تأیید', exact=True).first.click()
    expect(page.locator('#detail-panel tbody')).to_contain_text('کاربر آزمایشی')
    passed('Acknowledge action refreshes the alert history')
    page.once('dialog', lambda d: d.accept())
    page.get_by_role('button', name='رفع', exact=True).first.click()
    expect(page.locator('.detail-pagination')).to_contain_text('۳۴')
    page.get_by_role('checkbox', name='نمایش رفع‌شده‌ها').check()
    expect(page.locator('.detail-pagination')).to_contain_text('۳۵')
    passed('Resolve and include-resolved switch update exact alert counts')
    page.goto(base + '/servers/5')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.locator('.detail-hero')).to_contain_text('عدم دسترسی')
    expect(page.get_by_role('alert')).to_contain_text('آخرین خطای اتصال')
    page.get_by_role('button', name='تست اتصال', exact=True).click()
    expect(page.locator('.detail-hero')).to_contain_text('سالم و تازه')
    passed('Disconnected detail and simulated test-connection refresh work')
    page.goto(base + '/servers/6')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.locator('.detail-hero')).to_contain_text('اطلاعات قدیمی')
    passed('Stale detail is not labelled healthy')
    page.goto(base + '/servers/8')
    page.wait_for_selector('main[data-preview-ready="true"]')
    page.get_by_role('tab', name='قطعات', exact=True).click()
    expect(page.get_by_role('heading', name='هنوز اطلاعات قطعات ثبت نشده است')).to_be_visible()
    page.get_by_role('tab', name='روند سلامت', exact=True).click()
    expect(page.get_by_role('heading', name='تاریخچه‌ای ثبت نشده است')).to_be_visible()
    passed('Never-polled server has informative empty states')
    page.goto(base + '/servers/1?fail=hardware')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.get_by_role('heading', name='ESXi-Production-01', exact=True)).to_be_visible()
    page.get_by_role('tab', name='قطعات', exact=True).click()
    expect(page.locator('#detail-panel [role=alert]')).to_contain_text('خطای آزمایشی')
    passed('Partial hardware failure does not hide server profile')
    page.goto(base + '/servers/999')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.get_by_role('alert')).to_contain_text('سرور پیدا نشد')
    passed('Missing/inaccessible server has an error and retry state')
    page.goto(base + '/servers/1?mode=viewer')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.get_by_role('heading', name='ESXi-Production-01', exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='تست اتصال', exact=True)).to_have_count(0)
    expect(page.get_by_role('link', name='ویرایش شناسنامه')).to_have_count(0)
    passed('View-only permissions hide mutating controls')
    page.goto(base + '/servers/1?mode=denied')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.get_by_role('alert')).to_contain_text('مجوز مشاهده')
    expect(page.get_by_role('tab')).to_have_count(0)
    passed('No-view permission hides all server content')
    page.goto(base + '/servers/1')
    page.wait_for_selector('main[data-preview-ready="true"]')
    page.get_by_role('link', name='ویرایش شناسنامه').click()
    expect(page.locator('.modal-title')).to_have_text('ویرایش سرور')
    page.get_by_role('button', name='انصراف', exact=True).click()
    passed('Edit link returns to correct company and opens the existing form')
    page.set_viewport_size({'width':390,'height':844})
    page.goto(base + '/servers')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.locator('.infra-metric')).to_have_count(8)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'Mobile dashboard overflows'
    page.screenshot(path=str(output / 'dashboard-mobile.png'))
    page.goto(base + '/servers/1')
    page.wait_for_selector('main[data-preview-ready="true"]')
    expect(page.get_by_role('heading', name='ESXi-Production-01', exact=True)).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'Mobile detail overflows'
    page.screenshot(path=str(output / 'server-detail-mobile.png'),full_page=True)
    page.get_by_role('tab', name='قطعات', exact=True).click()
    expect(page.locator('#detail-panel tbody tr')).to_have_count(6)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'Mobile table overflows viewport'
    passed('390px mobile dashboard, detail and hardware tab stay within viewport')
    assert not errors, errors
    passed('No JavaScript page errors across navigation and component disposal')
    browser.close()

(output / 'browser-results.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'errors':errors,'fixture_only':True},ensure_ascii=False,indent=2))
print(f'SUCCESS: {len(checks)} browser scenarios passed; fixture API, real Blazor components.')
