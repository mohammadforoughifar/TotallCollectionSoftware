def crop_whitespace(src):
    """حاشیهٔ خالی پایین/کنار تصویر را می‌بُرد تا تصویر در صفحه بزرگ‌تر دیده شود."""
    from PIL import Image, ImageChops
    im = Image.open(src).convert("RGB")
    bg = Image.new("RGB", im.size, im.getpixel((3, im.height - 3)))
    diff = ImageChops.difference(im, bg)
    box = diff.getbbox()
    if not box:
        return src
    pad = 14
    box = (max(0, box[0] - pad), max(0, box[1] - pad),
           min(im.width, box[2] + pad), min(im.height, box[3] + pad))
    out = CROPPED / Path(src).name
    im.crop(box).save(out, "PNG", optimize=True)
    return str(out)
