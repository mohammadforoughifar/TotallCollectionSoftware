#!/usr/bin/env python3
"""یادداشت اصلاح: دسترسی به دکمهٔ «پیش‌نویس امضا» پس از ثبت تأیید هویت."""
import sys
from pathlib import Path

sys.path.insert(0, "/home/user/tools")
from pdfkit_fa import Guide, fa_num  # noqa: E402

SHOTS = Path("/home/user/.shots")
OUT = Path("/home/user/اصلاح-دکمه-پیش-نویس.pdf")


def crop(src: Path) -> Path:
    from PIL import Image, ImageChops
    im = Image.open(src).convert("RGB")
    bg = Image.new("RGB", im.size, im.getpixel((3, im.height - 3)))
    box = ImageChops.difference(im, bg).getbbox()
    out = SHOTS / ("c-" + src.name)
    if not box:
        return src
    pad = 14
    box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad))
    im.crop(box).save(out, "PNG", optimize=True)
    return out


def ensure(g, need_mm: float) -> None:
    """اگر فضای صفحه کمتر از نیاز است، صفحهٔ تازه باز کن (تا عنوان از تصویر جدا نشود)."""
    if g.get_y() + need_mm > 272:
        g.add_page()


def main() -> None:
    g = Guide("اصلاح دکمهٔ پیش‌نویس")
    g.cover_page(
        "دسترسی به «پیش‌نویس امضا» و «امضا»",
        "گزارش اصلاح — پنل پشتیبانی لایسنس",
        "پس از ثبت تأیید هویت، دکمه‌های بعدی برای نقش مدیر نمایش داده نمی‌شد. "
        "این گزارش علت، اصلاح و نتیجهٔ آزمون واقعی در مرورگر را نشان می‌دهد.",
        [("نسخه", "۱۴۰۵/۰۸/۲۴"), ("نقش آزمون‌شده", "مدیر (Admin)"), ("پرونده‌های آزمون", "REQ-1405-0005 … 0010")],
        "بدون هیچ رمز، توکن یا کلید در این سند.",
    )

    g.h1("۱) چه اتفاقی افتاده بود", fa_num(1))
    g.p("در صفحهٔ «پروندهٔ درخواست»، دکمه‌های بالای صفحه فقط در یک حالت خاص رندر می‌شدند: "
        "«پیش‌نویس امضا» و «امضا» تنها وقتی وضعیت پرونده از قبل «تأییدشده» بود. "
        "اما رسیدن به «تأییدشده» خودش یک قدم است: پس از ثبت تأیید هویت باید وضعیت عوض شود. "
        "برای همین کاربر با نقش مدیر، بعد از ثبت تأیید هویت، هیچ دکمه‌ای برای ادامه نمی‌دید — "
        "دکمهٔ تأیید در پایین صفحه و در کارت «تغییر وضعیت» پنهان بود.")
    g.callout("warn", "قاعده‌های سرور درست بودند؛ مشکل فقط «راهنمای گام بعدی» در رابط کاربری بود: "
                      "دکمهٔ پیش‌نویس تا وضعیت «تأییدشده» رندر نمی‌شد و راهی برای فهمیدن این نکته در صفحه نبود.")

    g.h1("۲) اصلاح انجام‌شده", fa_num(2))
    g.bullets([
        "دکمه‌های صفحه‌سر گام‌آگاه شدند: بدون هویت → «ثبت تأیید هویت»؛ هویت ثبت‌شده و وضعیت «بررسی» → دکمهٔ «تأیید درخواست»؛ پس از تأیید → «پیش‌نویس امضا» (یا «ویرایش پیش‌نویس») و «امضا»؛ پس از صدور → «تحویل لایسنس».",
        "کارت تازهٔ «قدم بعدی» با شش گام و نشان «انجام شد / باقی‌مانده»: مشتری، تأیید هویت، تأییدشده، پیش‌نویس، صدور فایل، تحویل.",
        "زیر همان کارت یک جملهٔ راهنما می‌گوید الان دقیقاً چه کاری باید بکنید.",
        "دکمهٔ «امضا» فقط برای نقش‌های «امضاکننده» و «مدیر» نمایش داده می‌شود؛ برای بقیه، نشان راهنما نشان داده می‌شود.",
        "هیچ قاعدهٔ امنیتی به کلاینت منتقل نشد: همهٔ بررسی‌ها همان‌جای قبلی در Workflow و RequestService است و هر POST دوباره اعتبارسنجی می‌شود.",
    ])

    g.h1("۳) نتیجهٔ آزمون واقعی (نقش مدیر)", fa_num(3))
    g.p("سه حالت با مرورگر واقعی و روی همین پنل اجرا شد؛ فهرست دکمه‌های صفحه‌سر در هر حالت:")
    g.table(["حالت پرونده", "دکمه‌های صفحه‌سر", "گام بعدی"],
            [["هویت ثبت شده، وضعیت «بررسی»", "تأیید درخواست", "با یک کلیک وارد وضعیت «تأییدشده» می‌شوید"],
             ["وضعیت «تأییدشده»، بدون پیش‌نویس", "پیش‌نویس امضا · امضا", "پیش‌نویس بسازید، سپس امضا"],
             ["پس از امضا (صادرشده)", "تحویل لایسنس", "تحویل به مشتری را ثبت کنید"]],
            widths=[62, 56, 58])

    g.h1("۴) تصویرها", fa_num(4))
    ensure(g, 150)
    g.h2("۴-۱) تأیید هویت ثبت شده، وضعیت «بررسی»")
    g.figure(str(crop(SHOTS / "v2-01-identity-to-approve.png")))
    g.legend([("دکمهٔ «تأیید درخواست» در صفحه‌سر", "با یک کلیک پرونده «تأییدشده» می‌شود"),
              ("کارت «قدم بعدی»", "شش گام با نشان انجام‌شدن"),
              ("جملهٔ راهنمای گام بعدی", "می‌گوید الان چه کاری لازم است")])

    ensure(g, 150)
    g.h2("۴-۲) پس از تأیید: دکمه‌های پیش‌نویس و امضا")
    g.figure(str(crop(SHOTS / "v2-02-approved-draft-sign.png")))
    g.legend([("«پیش‌نویس امضا»", "ساخت یا ویرایش پیش‌نویس لایسنس"),
              ("«امضا»", "تنها برای نقش امضاکننده/مدیر"),
              ("گام ۳ «انجام شد»", "وضعیت تأییدشده ثبت شد")])

    ensure(g, 150)
    g.h2("۴-۳) پس از امضا: دکمهٔ تحویل")
    g.figure(str(crop(SHOTS / "v2-03-issued-deliver.png")))
    g.legend([("«تحویل لایسنس»", "ثبت تحویل و ایمیل/دانلود")])
    g.callout("ok", "آزمون کامل شد: پروندهٔ آزمون با سریال LIC-20261115-6BCB44 امضا و صادر شد و "
                    "پنل با کلید عمومی آن را بازبینی کرد.")

    g.h1("۵) اگر باز هم دکمه‌ای ندیدید", fa_num(5))
    g.bullets([
        "کارت «قدم بعدی» را بخوانید؛ اولین گام «باقی‌مانده» همان کاری است که باید انجام شود.",
        "اگر گام «مشتری» باقی است، بدون مشتری پیش‌نویس ساخته نمی‌شود («مشتری این درخواست مشخص نیست»).",
        "اگر نقش شما «اپراتور» است، دکمهٔ امضا عمداً نمایش داده نمی‌شود؛ امضا با نقش امضاکننده یا مدیر است.",
        "مرورگر را تازه کنید (Ctrl+F5)؛ دکمه‌ها سمت سرور رندر می‌شوند و کش قدیمی می‌تواند صفحهٔ قبلی را نشان دهد.",
    ])

    g.output(str(OUT))
    print("ساخته شد:", OUT)


if __name__ == "__main__":
    main()
