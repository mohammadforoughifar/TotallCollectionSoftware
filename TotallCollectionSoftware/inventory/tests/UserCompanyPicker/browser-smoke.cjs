// Runs against BrowserHost with fixture data only, never the production API.
const { chromium, expect } = require('playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const baseUrl = process.env.PICKER_TEST_URL || 'http://127.0.0.1:5127';
const screenshots = process.env.PICKER_SCREENSHOTS;
let checks = 0;
const pass = message => { checks++; console.log('PASS: ' + message); };

(async () => {
    const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
    const errors = [];
    try {
        const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
        const page = await context.newPage();
        page.on('pageerror', error => errors.push(error.message));
        const info = await page.request.get(baseUrl + '/fixture/info');
        expect(info.ok(), 'Refuse to run against anything except the fixture-only host').toBeTruthy();
        expect(await info.json()).toEqual({ fixture: 'UserCompanyPicker', syntheticData: true });
        expect((await page.request.post(baseUrl + '/fixture/reset')).ok()).toBeTruthy();
        await page.goto(baseUrl);
        await page.getByRole('button', { name: /کاربر جدید/ }).click();
        const modal = page.locator('.modal:visible');
        const trigger = page.locator('#user-company-picker');
        const menu = page.locator('.check-combo-menu');
        const search = page.getByRole('searchbox', { name: 'جستجوی نام یا شناسهٔ کمپانی…' });
        await trigger.click();
        await expect(search).toBeFocused();
        pass('desktop: opening the check combo focuses its search field');
        await search.fill('كيان');
        await expect(menu.getByRole('checkbox')).toHaveCount(1);
        await menu.getByRole('checkbox').check();
        await expect(page.getByRole('button', { name: 'حذف شرکت کیان', exact: true })).toBeVisible();
        await search.fill('پارس');
        await expect(menu.getByRole('checkbox')).toHaveCount(1);
        await menu.getByRole('checkbox').check();
        await expect(trigger).toContainText('۲');
        await expect(menu).toBeVisible();
        await expect(search).toHaveValue('پارس');
        pass('desktop: checkbox multi-selection preserves choices and the search without closing');
        await search.fill('');
        await expect(menu.getByRole('checkbox')).toHaveCount(65);
        await expect(menu.locator('input:checked')).toHaveCount(2);
        await expect.poll(() => menu.locator('.check-combo-options').evaluate(el => el.scrollHeight > el.clientHeight)).toBeTruthy();
        pass('desktop: every company remains reachable in the scrollable checklist');
        await search.fill('۲۰۵۹');
        await expect(menu.getByRole('checkbox')).toHaveCount(1);
        await menu.getByRole('checkbox').check();
        await expect(trigger).toContainText('۳');
        await menu.getByRole('checkbox').uncheck();
        await expect(trigger).toContainText('۲');
        pass('desktop: Persian ID search can select and unselect a company beyond the first fifty');
        await search.fill('no-match');
        await expect(menu.getByRole('status').first()).toContainText('موردی با این جستجو پیدا نشد');
        await expect(page.locator('.check-combo-chip')).toHaveCount(2);
        pass('desktop: unmatched search leaves selected chips intact');
        await search.press('Escape');
        await expect(menu).toHaveCount(0);
        await expect(modal).toBeVisible();
        await expect(trigger).toBeFocused();
        pass('desktop: Escape closes only the dropdown under the actual application hotkey handler');
        await trigger.press('Enter');
        await expect(search).toBeFocused();
        await search.fill('۱۰۰۱');
        await expect(menu.getByRole('checkbox')).toHaveCount(1);
        await menu.getByRole('checkbox').focus();
        await menu.getByRole('checkbox').press('Space');
        await expect(trigger).toContainText('۱');
        await menu.getByRole('checkbox').press('Space');
        await expect(trigger).toContainText('۲');
        pass('desktop: native keyboard Enter and Space operate the trigger and checkboxes');
        await search.fill('');
        if (screenshots) {
            fs.mkdirSync(screenshots, { recursive: true });
            await page.screenshot({ path: path.join(screenshots, 'company-picker-desktop.png') });
        }
        await page.locator('.pop-overlay').click({ position: { x: 4, y: 4 } });
        await expect(menu).toHaveCount(0);
        await expect(modal).toBeVisible();
        await expect(page.locator('.check-combo-chip')).toHaveCount(2);
        pass('desktop: clicking outside dismisses the list, not the form or its selections');
        await page.getByRole('button', { name: 'حذف شرکت کیان', exact: true }).click();
        await expect(page.locator('.check-combo-chip')).toHaveCount(1);
        pass('desktop: selected chips support individual removal');
        await modal.getByRole('button', { name: 'انصراف (Esc)', exact: true }).click();
        await page.locator('table button[title="ویرایش"]').first().click();
        await expect(trigger).toBeEnabled();
        await expect(page.locator('.check-combo-chip')).toHaveCount(2);
        await trigger.click();
        await expect(menu.locator('input:checked')).toHaveCount(2);
        pass('desktop: edit form prechecks the user’s saved company assignments');
        await search.fill('پارس');
        await expect(menu.getByRole('checkbox')).toHaveCount(1);
        await menu.getByRole('checkbox').uncheck();
        await search.fill('omega');
        await expect(menu.getByRole('checkbox')).toHaveCount(1);
        await menu.getByRole('checkbox').check();
        await expect(trigger).toContainText('۲');
        await menu.getByRole('button', { name: 'بستن فهرست', exact: true }).click();
        await modal.locator('[data-hotkey="f1"]').click();
        await expect(modal).toHaveCount(0);
        const assignments = await (await page.request.get(baseUrl + '/fixture/assignments')).json();
        expect(assignments.at(-1)).toEqual({ userId: 11, companyIds: [1001, 1003] });
        pass('desktop: real form save sends the selected company IDs to the unchanged endpoint');
        await page.request.post(baseUrl + '/fixture/access-error/true');
        await page.locator('table button[title="ویرایش"]').first().click();
        await expect(modal.getByRole('alert')).toContainText('کمپانی‌های کاربر دریافت نشدند');
        await expect(modal.locator('[data-hotkey="f1"]')).toBeDisabled();
        await page.request.post(baseUrl + '/fixture/access-error/false');
        await modal.getByRole('button', { name: 'تلاش دوباره', exact: true }).click();
        await expect(trigger).toBeEnabled();
        await expect(modal.locator('[data-hotkey="f1"]')).toBeEnabled();
        pass('desktop: failed access read blocks saving until a successful retry');
        await context.close();

        const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
        const phone = await mobile.newPage();
        phone.on('pageerror', error => errors.push(error.message));
        await phone.goto(baseUrl);
        await phone.getByRole('button', { name: /کاربر جدید/ }).tap();
        await phone.locator('#user-company-picker').tap();
        const mobileMenu = phone.locator('.check-combo-menu');
        const mobileSearch = mobileMenu.getByRole('searchbox');
        await expect(mobileSearch).toBeFocused();
        const bounds = await mobileMenu.boundingBox();
        expect(bounds.x).toBeGreaterThanOrEqual(0);
        expect(bounds.y).toBeGreaterThanOrEqual(0);
        expect(bounds.x + bounds.width).toBeLessThanOrEqual(391);
        expect(bounds.y + bounds.height).toBeLessThanOrEqual(845);
        pass('mobile: floating checklist stays within the narrow viewport');
        await mobileSearch.fill('كيان');
        await expect(mobileMenu.getByRole('checkbox')).toHaveCount(1);
        await mobileMenu.locator('.check-combo-option').tap();
        await expect(phone.locator('#user-company-picker')).toContainText('۱');
        await mobileSearch.fill('پارس');
        await expect(mobileMenu.getByRole('checkbox')).toHaveCount(1);
        await mobileMenu.locator('.check-combo-option').tap();
        await expect(phone.locator('#user-company-picker')).toContainText('۲');
        await expect(mobileMenu).toBeVisible();
        pass('mobile: touch selection supports multiple checked companies without losing focus or choices');
        if (screenshots) await phone.screenshot({ path: path.join(screenshots, 'company-picker-mobile.png') });
        await mobileMenu.getByRole('button', { name: 'بستن فهرست', exact: true }).tap();
        await expect(mobileMenu).toHaveCount(0);
        await expect(phone.locator('.check-combo-chip')).toHaveCount(2);
        pass('mobile: closing the dropdown preserves both selected chips');
        await mobile.close();
        expect(errors).toEqual([]);
        pass('no browser JavaScript errors during desktop and touch workflows');
        console.log(`ALL ${checks} BROWSER CHECKS PASSED.`);
    } finally {
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
