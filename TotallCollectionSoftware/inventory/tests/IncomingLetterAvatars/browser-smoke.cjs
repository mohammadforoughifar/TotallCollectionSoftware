// Use only the synthetic fixture host. The marker is checked before any test action.
const { chromium, expect } = require('playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.INCOMING_TEST_URL || 'http://127.0.0.1:5133';
