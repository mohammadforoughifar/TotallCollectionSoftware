const photo = (scope, id) => scope.locator(`img.user-avatar[src*="/api/auth/users/photo/${id}?"]`);
const rowMenu = row => row.locator('.dd > button:not(.star-btn)');
async function loaded(image) {
    await expect(image).toHaveCount(1);
    await expect.poll(() => image.evaluate(e => e.complete && e.naturalWidth > 0)).toBeTruthy();
}
async function allPhotos(scope, ids = [11, 21, 31, 32]) {
    for (const id of ids) await loaded(photo(scope, id).first());
    await expect(scope.locator('img[src*="/api/SystemUsers/photo/"]')).toHaveCount(0);
}
async function saveShot(page, name) {
    if (!screenshots) return;
    fs.mkdirSync(screenshots, { recursive: true });
    await page.screenshot({ path: path.join(screenshots, name + '.png') });
}
async function state(page) { return (await page.request.get(base + '/fixture/state')).json(); }
async function openFromList(page) {
    const row = page.locator('.pane .mail').first();
    await rowMenu(row).click();
    await row.locator('.ltmenu').getByRole('button', { name: /گردش نامه/ }).click();
    // Position:fixed overlay; the outer .ltx itself has no layout height.
    await expect(page.locator('.incoming-letter-gardesh .gmodal')).toBeVisible();
    await expect(page.locator('.incoming-letter-gardesh .gmodal')).toHaveCSS('opacity', '1');
}
async function openFullView(page) {
    const row = page.locator('.pane .mail').first();
    await rowMenu(row).click();
    await row.locator('.ltmenu').getByRole('button', { name: /مشاهده کامل/ }).click();
    await expect(page.locator('.incoming-letter-view .sheet')).toBeVisible();
    await allPhotos(page.locator('.incoming-letter-view'));
}
async function fits(page, element) {
    // Measure settled layout, not the intentional slide-in/pop entrance transform.
    await element.evaluate(async e => { await Promise.all(e.getAnimations().map(a => a.finished)); });
    const box = await element.boundingBox();
    const width = page.viewportSize().width;
    expect(box.x).toBeGreaterThanOrEqual(0);
    expect(box.x + box.width).toBeLessThanOrEqual(width + 1);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
}
