// Fixture-only interactive test of the actual Roles component; never use a production server.
const { chromium, expect } = require('playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.ROLE_TEST_URL || 'http://127.0.0.1:5129';
const screenshots = process.env.ROLE_SCREENSHOTS;
let checks = 0;
const pass = message => { checks++; console.log('PASS: ' + message); };

(async () => {
    const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
    const errors = [];
    try {
        const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
        const page = await context.newPage();
        page.on('pageerror', error => errors.push(error.message));
        const info = await page.request.get(base + '/fixture/info');
        expect(info.ok(), 'Refuse to operate without the fixture-only marker').toBeTruthy();
        expect(await info.json()).toEqual({ fixture: 'RoleGroupSelection', syntheticData: true });
        expect((await page.request.post(base + '/fixture/reset')).ok()).toBeTruthy();
        const catalog = await (await page.request.get(base + '/fixture/catalog')).json();
        const work = catalog.categories.find(c => c.modules.includes('WorkOrders'));
        const finance = catalog.categories.find(c => c.modules.includes('Moadian'));
        const workIds = catalog.permissions.filter(p => work.modules.includes(p.module)).map(p => p.id);
        await page.goto(base);
        await page.getByRole('button', { name: /ایجاد نقش جدید/ }).click();
        const modal = page.locator('.modal:visible');
        const search = modal.getByPlaceholder('جستجوی ماژول یا دسترسی…');
        const groupButton = (title, filtered = false) => page.getByRole('checkbox', {
            name: `${filtered ? 'انتخاب نتایج' : 'انتخاب همه'} در گروه ${title}`, exact: true
        });
        await expect(page.locator('.perm-tree-category > summary .perm-select-all')).toHaveCount(catalog.categories.length + 1);
        pass('desktop: each category, including Other, exposes select all in its header');
        await expect(page.locator('.perm-tree-category > summary .perm-tree-actions').first()).toHaveCSS('opacity', '1');
        pass('desktop: bulk actions stay visibly opaque without hover, independent of shared tree styles');
        const workButton = groupButton(work.title);
        const workTree = workButton.locator('xpath=ancestor::details[1]');
        await expect(workTree).toHaveJSProperty('open', false);
        await workButton.click();
        await expect(workButton).toHaveAttribute('aria-checked', 'true');
        await expect(workTree.locator('.perm-leaf input:checked')).toHaveCount(workIds.length);
        await expect(workTree).toHaveJSProperty('open', false);
        pass('desktop: selecting a collapsed group checks all its children without opening the tree');
        await workTree.locator(':scope > summary .tree-title').click();
        await expect(workTree).toHaveJSProperty('open', true);
        const workModule = workTree.locator('.perm-tree-module').filter({ has: page.locator('span[title="WorkOrders"]') });
        const moduleButton = workModule.locator(':scope > summary .perm-select-all');
        await moduleButton.click();
        await expect(moduleButton).toHaveAttribute('aria-checked', 'false');
        await expect(workButton).toHaveAttribute('aria-checked', 'mixed');
        await expect(workTree.locator('.perm-leaf input:checked')).toHaveCount(workIds.length - 2);
        pass('desktop: clearing one module preserves sibling modules and marks the parent as mixed');
        await moduleButton.click();
        await workModule.locator(':scope > summary .tree-title').click();
        await workModule.locator('.perm-leaf input').first().uncheck();
        await expect(moduleButton).toHaveAttribute('aria-checked', 'mixed');
        await expect(workButton).toHaveAttribute('aria-checked', 'mixed');
        await moduleButton.focus();
        await moduleButton.press('Space');
        await expect(moduleButton).toHaveAttribute('aria-checked', 'true');
        await expect(workButton).toHaveAttribute('aria-checked', 'true');
        await expect(workModule).toHaveJSProperty('open', true);
        pass('desktop: partial selection is visible and Space selects the remaining items without folding');
        await workButton.focus();
        await workButton.press('Enter');
        await expect(workButton).toHaveAttribute('aria-checked', 'false');
        await expect(workTree.locator('.perm-leaf input:checked')).toHaveCount(0);
        pass('desktop: Enter on a fully selected group clears only that group');
        const viewLeaf = workModule.locator('.perm-leaf').filter({ has: page.locator('small[title="WorkOrders.View"]') });
        await viewLeaf.locator('input').check();
        await search.fill('Create');
        const filteredWork = groupButton(work.title, true);
        await expect(filteredWork).toBeVisible();
        await filteredWork.click();
        await expect(filteredWork).toHaveAttribute('aria-checked', 'true');
        await expect(modal.getByRole('status')).toContainText('سایر دسترسی‌ها تغییر نمی‌کنند');
        await search.fill('');
        await expect(workButton).toHaveAttribute('aria-checked', 'mixed');
        await expect(workTree.locator('.perm-leaf input:checked')).toHaveCount(4);
        pass('desktop: filtered select-all changes only matching actions and keeps a hidden selected View');
        await search.fill('Create');
        await expect(filteredWork).toBeVisible();
        await filteredWork.click();
        await expect(filteredWork).toHaveAttribute('aria-checked', 'false');
        await search.fill('');
        await expect(workTree.locator('.perm-leaf input:checked')).toHaveCount(1);
        await expect(viewLeaf.locator('input')).toBeChecked();
        pass('desktop: filtered clear never removes hidden selected permissions');
        await search.fill('no-matching-permission');
        await expect(page.locator('.perm-tree-category')).toHaveCount(0);
        await search.fill('');
        await expect(workTree.locator('.perm-leaf input:checked')).toHaveCount(1);
        pass('desktop: an empty search result does not reset existing selections');

        const otherButton = groupButton('سایر');
        const otherTree = otherButton.locator('xpath=ancestor::details[1]');
        await otherButton.click();
        await expect(otherTree.locator('.perm-leaf input:checked')).toHaveCount(4);
        await expect(workTree.locator('.perm-leaf input:checked')).toHaveCount(1);
        await otherTree.locator(':scope > summary .tree-title').click();
        const alpha = otherTree.locator('.perm-tree-module').filter({ has: page.locator('span[title="CustomAlpha"]') });
        await alpha.locator(':scope > summary .perm-select-all').click();
        await expect(otherButton).toHaveAttribute('aria-checked', 'mixed');
        await expect(otherTree.locator('.perm-leaf input:checked')).toHaveCount(2);
        pass('desktop: Other and each of its modules have independent bulk selection');
        await search.fill('CustomAlpha');
        const filteredOther = groupButton('سایر', true);
        await expect(filteredOther).toBeVisible();
        await filteredOther.click();
        await expect(filteredOther).toHaveAttribute('aria-checked', 'true');
        await filteredOther.click();
        await expect(filteredOther).toHaveAttribute('aria-checked', 'false');
        await search.fill('');
        await expect(otherTree.locator('.perm-leaf input:checked')).toHaveCount(2);
        pass('desktop: Other uses the same search-safe select/clear behavior');
        await groupButton(finance.title).click();
        await expect(groupButton(finance.title)).toHaveAttribute('aria-checked', 'true');
        await expect(page.locator('small[title="Moadian.Configure"]')).toHaveCount(0);
        await expect(page.locator('small[title="Moadian.ProviderInvoices"]')).toHaveCount(0);
        pass('desktop: legacy hidden Moadian actions are excluded from group selection');
        if (screenshots) {
            fs.mkdirSync(screenshots, { recursive: true });
            await workButton.scrollIntoViewIfNeeded();
            await page.screenshot({ path: path.join(screenshots, 'roles-select-all-desktop.png') });
        }
        const selectedKeys = await page.locator('.perm-leaf').evaluateAll(leaves => leaves
            .filter(l => l.querySelector('input').checked).map(l => l.querySelector('small').title));
        const expectedIds = catalog.permissions.filter(p => selectedKeys.includes(`${p.module}.${p.action}`)).map(p => p.id).sort((a,b) => a-b);
        await modal.getByPlaceholder('مثال: مدیر سیستم').fill('نقش گروهی آزمایشی');
        await modal.getByRole('button', { name: 'ذخیره نقش', exact: true }).click();
        await expect(modal).toHaveCount(0);
        const saves = await (await page.request.get(base + '/fixture/saves')).json();
        expect(saves.at(-1).method).toBe('POST');
        expect(saves.at(-1).role.permissionIds.sort((a,b) => a-b)).toEqual(expectedIds);
        pass('desktop: Save role sends exactly the chosen IDs through the unchanged API contract');
        await page.locator('button[title="ویرایش نقش"]').first().click();
        await expect(workButton).toHaveAttribute('aria-checked', 'mixed');
        await groupButton('سایر').click();
        await modal.getByRole('button', { name: 'انصراف', exact: true }).click();
        await page.locator('button[title="ویرایش نقش"]').first().click();
        await expect(groupButton('سایر')).toHaveAttribute('aria-checked', 'false');
        await expect(workButton).toHaveAttribute('aria-checked', 'mixed');
        pass('desktop: edit restores existing partial selection and cancellation discards unsaved bulk changes');
        await context.close();

        const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
        const phone = await mobile.newPage();
        phone.on('pageerror', error => errors.push(error.message));
        await phone.goto(base);
        await phone.getByRole('button', { name: /ایجاد نقش جدید/ }).tap();
        const firstTitle = catalog.categories[0].title;
        const phoneButton = phone.getByRole('checkbox', { name: `انتخاب همه در گروه ${firstTitle}`, exact: true });
        await phoneButton.scrollIntoViewIfNeeded();
        const bounds = await phoneButton.boundingBox();
        await expect(phoneButton.locator('..')).toHaveCSS('opacity', '1');
        expect(bounds.x).toBeGreaterThanOrEqual(0);
        expect(bounds.x + bounds.width).toBeLessThanOrEqual(391);
        expect(await phone.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
        pass('mobile: long category headings and selection controls fit the viewport without horizontal overflow');
        await phoneButton.tap();
        await expect(phoneButton).toHaveAttribute('aria-checked', 'true');
        const phoneTree = phoneButton.locator('xpath=ancestor::details[1]');
        await expect(phoneTree).toHaveJSProperty('open', false);
        await phoneButton.tap();
        await expect(phoneButton).toHaveAttribute('aria-checked', 'false');
        pass('mobile: touch select/clear does not accidentally expand or collapse the category');
        if (screenshots) await phone.screenshot({ path: path.join(screenshots, 'roles-select-all-mobile.png') });
        await mobile.close();
        expect(errors).toEqual([]);
        pass('no JavaScript errors during desktop or touch interactions');
        console.log(`ALL ${checks} ROLE-GROUP BROWSER CHECKS PASSED.`);
    } finally {
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
