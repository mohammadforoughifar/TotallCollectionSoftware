    /// دو جدول هم‌پوشانی ندارند: کدهای برگشتی همیشه ۲۰۰ یا بزرگ‌تر و وضعیت‌های پیامک همیشه
    /// ۱۰۰ یا کوچک‌تر هستند، و سرور هم دقیقاً یکی از این دو را انتخاب و ذخیره می‌کند
